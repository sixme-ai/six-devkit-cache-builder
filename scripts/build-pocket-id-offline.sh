#!/usr/bin/env bash
set -euo pipefail
umask 077

RELEASE="v2.19.1"
BINARY_SHA256="fbe58b3af6e225600136c7da033810d2d86436fbd13a135fa52205f467544436"
BINARY_URL="https://github.com/pocket-id/pocket-id/releases/download/$RELEASE/pocket-id_linux_amd64"
LICENSE_URL="https://raw.githubusercontent.com/pocket-id/pocket-id/$RELEASE/LICENSE"
DIST_NAME="pocket-id-offline-linux-amd64-v2.19.1.zip"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
BUNDLE="$WORK/pocket-id-offline"
mkdir -p "$BUNDLE" dist
curl -fL --retry 3 --retry-delay 2 --connect-timeout 20 --max-time 240 "$BINARY_URL" -o "$BUNDLE/pocket-id"
printf '%s  %s\n' "$BINARY_SHA256" "$BUNDLE/pocket-id" | sha256sum -c -
chmod 755 "$BUNDLE/pocket-id"
curl -fL --retry 3 --connect-timeout 20 --max-time 40 "$LICENSE_URL" -o "$BUNDLE/LICENSE.pocket-id"

cat > "$BUNDLE/start.sh" <<'RUNNER'
#!/usr/bin/env bash
set -euo pipefail
umask 077
cd "$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
if [[ ! -f .env ]]; then
  command -v openssl >/dev/null 2>&1 || { echo "openssl is required to create local secrets" >&2; exit 2; }
  KEY=$(openssl rand -hex 32)
  ADMIN_API_KEY=$(openssl rand -hex 32)
  cat > .env <<ENVFILE
APP_URL=http://localhost:1411
INTERNAL_APP_URL=http://localhost:1411
HOST=127.0.0.1
PORT=1411
ENCRYPTION_KEY=$KEY
STATIC_API_KEY=$ADMIN_API_KEY
VERSION_CHECK_DISABLED=true
ANALYTICS_DISABLED=true
ICON_LIBRARY_URL=disabled
ALLOW_INSECURE_CALLBACK_URLS=false
ENVFILE
  chmod 600 .env
  printf 'Generated private local .env (chmod 600) and SQLite data directory.\n'
fi
mkdir -p data
chmod 700 data
exec ./pocket-id
RUNNER
chmod 755 "$BUNDLE/start.sh"

cat > "$BUNDLE/check-oidc.sh" <<'CHECK'
#!/usr/bin/env bash
set -euo pipefail
URL="http://localhost:1411"
curl --noproxy '*' -fsS --connect-timeout 3 --max-time 6 "$URL/.well-known/openid-configuration" | python3 -c 'import json,sys; d=json.load(sys.stdin); assert d["issuer"]=="http://localhost:1411",d.get("issuer"); assert d["jwks_uri"].startswith("http://localhost:1411/"); print("OIDC discovery PASS; issuer="+d["issuer"]); print("JWKS="+d["jwks_uri"])'
JWKS=$(curl --noproxy '*' -fsS --max-time 6 "$URL/.well-known/openid-configuration" | python3 -c 'import json,sys; print(json.load(sys.stdin)["jwks_uri"])')
curl --noproxy '*' -fsS --max-time 6 "$JWKS" | python3 -c 'import json,sys; d=json.load(sys.stdin); assert len(d["keys"])>=1; print("JWKS PASS; signing keys="+str(len(d["keys"])))'
CHECK
chmod 755 "$BUNDLE/check-oidc.sh"
cp scripts/agent-m2m.sh "$BUNDLE/agent-m2m.sh"
chmod 755 "$BUNDLE/agent-m2m.sh"

cat > "$BUNDLE/README.md" <<'README'
# Pocket ID v2.19.1 — standalone offline Linux amd64

This package redistributes the upstream Pocket ID binary under BSD-2-Clause.
It contains no private application source, secrets, pre-created user, or shared IdP state.

## Start (network disconnected)

1. Extract the ZIP. Run: `cd pocket-id-offline && ./start.sh`
2. Open `http://localhost:1411/setup` from a browser **on the same computer** for user/passkey setup (optional for admin API / client-credential tests).
3. Run `./check-oidc.sh` in another terminal to verify OIDC issuer and JWKS over loopback.
5. For **browserless local OAuth tokens**, run `./agent-m2m.sh provision` once, then `./agent-m2m.sh verify`. The client credentials remain private to this terminal; M2M does not replace user-login Code+PKCE.
4. The launcher creates `.env` with **random secrets**, `chmod 600`, and a private SQLite `data` directory. Do not commit, export, share or publish these runtime files.

**No internet required at runtime**. Outbound release checks, analytics and remote icon search are disabled. Loopback HTTP only. A fresh agent session can create its own independent local issuer and keys without using any cloud identity provider.

### Scope

The server is the **actual official** Pocket ID executable with its embedded frontend and SQLite. Use a private `STATIC_API_KEY` from the generated `.env` to provision local OIDC clients and API resources through the official admin REST API. For noninteractive local tests, Pocket ID supports OAuth2 `client_credentials` for an explicitly authorized client/API resource and scope. Never copy a token generated by one isolated session to another session.

Browser passkeys are supported only at `localhost` or HTTPS; headless agent terminals cannot perform real human passkey ceremonies by themselves. ChatGPT/Claude remote OAuth and external IdP E2E are separate QA workflows and are **not** implied by this package. This localhost IdP also does not fix functional application MCP/JWT integration failures by itself.

### Integrity

Official upstream release binary `pocket-id_linux_amd64` v2.19.1
SHA-256: `fbe58b3af6e225600136c7da033810d2d86436fbd13a135fa52205f467544436`

The bundle includes original BSD-2-Clause license. The archive SHA-256 is next to the ZIP in the GitHub Release. The original binary checksum was verified in GitHub Actions before packaging.

No Docker, Node.js, Go, PostgreSQL or Maven is needed to run Pocket ID.
README
printf '%s  %s\n' "$BINARY_SHA256" "pocket-id" > "$BUNDLE/pocket-id.sha256"

# Exercise a real executable and OIDC service in an isolated fresh working directory.
SMOKE="$WORK/smoke"
cp -a "$BUNDLE" "$SMOKE"
( cd "$SMOKE" && exec ./start.sh ) > "$WORK/smoke.log" 2>&1 &
SERVER_PID=$!
cleanup_server() {
  kill "$SERVER_PID" 2>/dev/null || true
  wait "$SERVER_PID" 2>/dev/null || true
}
trap 'cleanup_server; rm -rf "$WORK"' EXIT
READY=0
for try in $(seq 1 80); do
  if curl --noproxy '*' -fsS --connect-timeout 1 --max-time 2 http://localhost:1411/.well-known/openid-configuration > "$WORK/discovery.json" 2>/dev/null; then
    READY=1
    break
  fi
  if ! kill -0 "$SERVER_PID" 2>/dev/null; then
    echo "Pocket ID exited during startup; server failed" >&2
    exit 1
  fi
  sleep 1
done
[[ "$READY" == 1 ]] || { echo "Pocket ID did not become ready" >&2; exit 1; }
( cd "$SMOKE" && ./check-oidc.sh )
( cd "$SMOKE" && ./agent-m2m.sh provision && ./agent-m2m.sh verify )
test -s "$SMOKE/data/pocket-id.db"
cleanup_server
trap 'rm -rf "$WORK"' EXIT
# Runtime smoke data and generated secrets were never copied back into BUNDLE.
test ! -e "$BUNDLE/.env"
test ! -e "$BUNDLE/.agent-m2m.json"
test ! -e "$BUNDLE/data"
( cd "$BUNDLE" && sha256sum -c pocket-id.sha256 )
test -s "$BUNDLE/LICENSE.pocket-id"

( cd "$WORK" && zip -q -r -9 "$OLDPWD/dist/$DIST_NAME" pocket-id-offline )
sha256sum "dist/$DIST_NAME" | sed 's#dist/##' > "dist/$DIST_NAME.sha256"
( cd dist && sha256sum -c "$DIST_NAME.sha256" && unzip -t "$DIST_NAME" )
printf 'Prepared %s\n' "dist/$DIST_NAME"
